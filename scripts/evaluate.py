"""Compare the three sharpening methods with numbers.

Test A - controlled blur (has a reference):
    The scan is treated as the reference. It is blurred further with a known
    Gaussian, then each method tries to undo that blur. PSNR and SSIM against
    the reference are measured inside the anatomy only (the black background
    is excluded, because it would inflate every score). Two blur levels are
    used so that no method wins only because its settings happen to match one
    blur.

Test B - the real blurred scan (no reference):
    Each method is applied to the scan with one moderate setting. Edge
    strength (higher = sharper), background noise (higher = more noise
    amplified) and clipped pixels (higher = more detail lost to pure black
    or white) are measured.

Writes results/controlled_test.csv, results/real_scan.csv, results/summary.md.
Run from the repository root:  python scripts/evaluate.py
"""

import csv
import os
import sys

import cv2
import numpy as np
from skimage.metrics import structural_similarity

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from sharpening import filters as F                      # noqa: E402
from sharpening import metrics as M                      # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "results")

BLUR_LEVELS = [(7, 1.5), (11, 2.5)]          # (kernel size, sigma) of the simulated blur

# Parameter grid for each method. Each entry: (label, function, kwargs, strength)
GRID = (
    [("laplacian", F.laplacian_sharpen, {"c": c}, c) for c in (0.25, 0.5, 1.0, 1.5, 2.0)]
    + [("unsharp", F.unsharp_mask, {"ksize": ks, "sigma": s, "k": k}, k)
       for ks, s in ((5, 1.0), (9, 2.0), (13, 3.0)) for k in (0.5, 1.0, 1.5, 2.0, 3.0)]
    + [("highpass", F.high_frequency_emphasis, {"d0": d0, "order": 2, "k": k}, k)
       for d0 in (30, 60, 100) for k in (0.5, 1.0, 2.0, 3.0)]
)

# One moderate setting per method for the real scan (Test B)
REAL_SETTINGS = [
    ("none", None, {}),
    ("laplacian", F.laplacian_sharpen, {"c": 1.0}),
    ("unsharp", F.unsharp_mask, {"ksize": 5, "sigma": 1.0, "k": 1.5}),
    ("highpass", F.high_frequency_emphasis, {"d0": 60, "order": 2, "k": 1.0}),
]


def roi_scores(reference, test, roi):
    diff = reference.astype(np.float64) - test.astype(np.float64)
    mse = float(np.mean(diff[roi] ** 2))
    psnr = 10 * np.log10(255 ** 2 / mse) if mse > 0 else float("inf")
    _, ssim_map = structural_similarity(reference, test, data_range=255, full=True)
    return psnr, float(ssim_map[roi].mean())


def fmt_params(kwargs):
    return " ".join(f"{k}={v}" for k, v in kwargs.items())


def controlled_test(reference):
    roi = ~M.flat_background_mask(reference, threshold=20, margin=5)
    rows = []
    for ks, sigma in BLUR_LEVELS:
        blurred = F.gaussian_blur(reference, ks, sigma)
        p, s = roi_scores(reference, blurred, roi)
        rows.append({"blur": f"{ks}x{ks} sigma={sigma}", "method": "none (blurred)",
                     "params": "", "strength": 0, "psnr_db": round(p, 2), "ssim": round(s, 4)})
        for name, fn, kwargs, strength in GRID:
            p, s = roi_scores(reference, fn(blurred, **kwargs), roi)
            rows.append({"blur": f"{ks}x{ks} sigma={sigma}", "method": name,
                         "params": fmt_params(kwargs), "strength": strength,
                         "psnr_db": round(p, 2), "ssim": round(s, 4)})
    return rows


def real_scan_test(scan):
    anatomy = ~M.flat_background_mask(scan, threshold=20, margin=0)
    background = M.flat_background_mask(scan, threshold=20, margin=15)
    rows = []
    for name, fn, kwargs in REAL_SETTINGS:
        out = scan if fn is None else fn(scan, **kwargs)
        rows.append({"method": name, "params": fmt_params(kwargs),
                     "edge_strength": round(M.edge_strength(out, anatomy), 2),
                     "background_noise": round(M.background_noise(out, background), 3),
                     "clipped_pct": round(100 * M.clipped_fraction(out), 2)})
    return rows


def write_csv(path, rows):
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def summary(ctrl, real):
    lines = ["# Results summary", "",
             "Generated by `scripts/evaluate.py`. Scores inside the anatomy only.", ""]
    for blur in dict.fromkeys(r["blur"] for r in ctrl):
        sub = [r for r in ctrl if r["blur"] == blur]
        base = sub[0]
        lines += [f"## Controlled test, simulated blur {blur}", "",
                  f"Blurred input before sharpening: PSNR {base['psnr_db']} dB, SSIM {base['ssim']}", "",
                  "| Method | Best setting (by SSIM) | PSNR (dB) | SSIM |", "|---|---|---|---|"]
        for m in ("laplacian", "unsharp", "highpass"):
            best = max((r for r in sub if r["method"] == m), key=lambda r: r["ssim"])
            lines.append(f"| {m} | {best['params']} | {best['psnr_db']} | {best['ssim']} |")
        lines.append("")
    lines += ["## Real blurred scan (no reference)", "",
              "| Method | Setting | Edge strength | Background noise | Clipped pixels (%) |",
              "|---|---|---|---|---|"]
    for r in real:
        lines.append(f"| {r['method']} | {r['params'] or '-'} | {r['edge_strength']} | "
                     f"{r['background_noise']} | {r['clipped_pct']} |")
    return "\n".join(lines) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    scan = cv2.imread(os.path.join(DATA, "xray_foot.png"), cv2.IMREAD_GRAYSCALE)
    if scan is None:
        sys.exit("data/xray_foot.png not found")
    ctrl = controlled_test(scan)
    real = real_scan_test(scan)
    write_csv(os.path.join(OUT, "controlled_test.csv"), ctrl)
    write_csv(os.path.join(OUT, "real_scan.csv"), real)
    text = summary(ctrl, real)
    with open(os.path.join(OUT, "summary.md"), "w") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
